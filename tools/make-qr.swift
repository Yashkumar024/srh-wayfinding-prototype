// Generates qr-codes.js: real QR codes (CoreImage, error correction M) for each route URL.
// Usage: swift tools/make-qr.swift <baseUrl> > qr-codes.js
//   e.g. swift tools/make-qr.swift https://yashkumar024.github.io/srh-wayfinding-prototype/route.html > qr-codes.js
import Foundation
import CoreImage

let base = CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "https://yashkumar024.github.io/srh-wayfinding-prototype/route.html"
let ids = ["c102", "b102", "lib", "event", "service"]
let ctx = CIContext()

func matrix(for text: String) -> [String] {
  let f = CIFilter(name: "CIQRCodeGenerator")!
  f.setValue(text.data(using: .utf8), forKey: "inputMessage")
  f.setValue("M", forKey: "inputCorrectionLevel")
  let img = f.outputImage!
  let w = Int(img.extent.width), h = Int(img.extent.height)
  var px = [UInt8](repeating: 0, count: w * h * 4)
  ctx.render(img, toBitmap: &px, rowBytes: w * 4, bounds: img.extent, format: .RGBA8, colorSpace: CGColorSpaceCreateDeviceRGB())
  var rows: [String] = []
  for y in 0..<h { var r = ""; for x in 0..<w { r += px[(y * w + x) * 4] < 128 ? "1" : "0" }; rows.append(r) }
  // CoreImage adds a quiet border; trim empty rows/columns so the data is modules only.
  let used = rows.indices.filter { rows[$0].contains("1") }
  let cols = (0..<w).filter { c in rows.contains { $0[$0.index($0.startIndex, offsetBy: c)] == "1" } }
  return used.map { r in String(cols.map { c in rows[r][rows[r].index(rows[r].startIndex, offsetBy: c)] }) }
}

var out = "/* Generated by tools/make-qr.swift — real QR codes for each route URL. Do not edit by hand. */\nwindow.ROUTE_BASE = \"\(base)\";\nwindow.QR_CODES = {\n"
// "home" opens the phone destination list (used by the QR on the home page)
for id in ids + ["home"] {
  let url = id == "home" ? base : "\(base)#\(id)"
  let m = matrix(for: url)
  out += "  \(id): { url: \"\(url)\", rows: [\n" + m.map { "    \"\($0)\"" }.joined(separator: ",\n") + "\n  ] },\n"
}
out += "};\n"
print(out, terminator: "")
